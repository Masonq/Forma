const VIEWS = { front: '230 20 470 1004', back: '820 20 470 1004' } as const

export function Anatomy({ levels, color = '#e23744', views = ['front', 'back'] }: {
  levels: Partial<Record<Muscle, number>>; color?: string; views?: ('front' | 'back')[]
}) {
  const active = (Object.keys(levels) as Muscle[])
    .filter((m) => (levels[m] ?? 0) > 0)
    .flatMap((m) => (ZONES[m] ?? []).map((d, i) => ({ k: m + i, d, v: Math.min(1, levels[m] ?? 0) })))
  return (
    <div className="anatomy" style={{ gridTemplateColumns: `repeat(${views.length}, 1fr)` }}>
      {views.map((vw) => (
        <svg key={vw} viewBox={VIEWS[vw]} role="img" aria-hidden="true">
          <defs>
            <filter id={`aglow-${vw}`} x="-40%" y="-40%" width="180%" height="180%"><feGaussianBlur stdDeviation="8" /></filter>
          </defs>
          <image href="/media/body.webp" x="0" y="0" width="1536" height="1024" />
          {/* мягкое свечение за активной мышцей */}
          <g filter={`url(#aglow-${vw})`}>
            {active.map(({ k, d, v }) => (
              <path key={k} d={d} fill={color} opacity={0.3 * v} />
            ))}
          </g>
          {/* заливка мышцы: яркость по нагрузке */}
          {active.map(({ k, d, v }) => (
            <path key={k} d={d} fill={color} opacity={0.45 + 0.55 * v} />
          ))}
          {/* контурные линии мышц поверх заливки */}
          <image href="/media/body-lines.webp" x="0" y="0" width="1536" height="1024" />
        </svg>
      ))}
    </div>
  )
}
