export function tr(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  const row = D[key]
  let s = row ? row[lang === 'ru' ? 0 : lang === 'en' ? 1 : 2] : key
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v))
  return s
}

export function plural(lang: Lang, n: number, key: string): string {
  const forms = tr(lang, key).split('|')
  if (lang === 'en') return n === 1 ? forms[0] : forms[1]
  const m10 = n % 10, m100 = n % 100
  if (m10 === 1 && m100 !== 11) return forms[0]
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return forms[1]
  return forms[2] ?? forms[1]
}

export function pick(lang: Lang, l3: L3): string {
  return l3[lang === 'ru' ? 0 : lang === 'en' ? 1 : 2]
}

export function useT() {
  const lang = useStore((s) => s.profile.lang)
  return {
    lang,
    t: (k: string, v?: Record<string, string | number>) => tr(lang, k, v),
    p: (n: number, k: string) => plural(lang, n, k),
    l: (x: L3) => pick(lang, x),
  }
}
